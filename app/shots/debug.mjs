import { webkit, devices } from '@playwright/test'
const browser = await webkit.launch()
const ctx = await browser.newContext({ ...devices['iPhone 15 Pro'] })
const page = await ctx.newPage()
page.on('pageerror', (e) => console.log('PAGEERROR', String(e).slice(0, 600)))
page.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && console.log('CONSOLE', m.text().slice(0, 400)))
await page.goto('http://localhost:5173/?seed=demo')
await page.waitForTimeout(4000); console.log("URL", page.url())
console.log(await page.evaluate(() => document.body.innerText.slice(0, 300)))
const r = await page.evaluate(async () => { try { const m = await import('/src/data/seed.ts'); await m.loadDemoSeed(); return 'ok' } catch (e) { return String(e && e.stack || e) } })
console.log('manual seed:', r)
await page.waitForTimeout(800)
console.log(await page.evaluate(() => document.body.innerText.slice(0, 300)))
await browser.close()
