import { webkit, devices } from '@playwright/test'
const browser = await webkit.launch()
const ctx = await browser.newContext({ ...devices['iPhone 15 Pro'], acceptDownloads: true })
const page = await ctx.newPage()
await page.goto('http://localhost:5173/?seed=demo')
await page.getByText('Onda · Day 4 of 14').waitFor({ timeout: 90000 })
const d = page.getByRole('button', { name: 'Dismiss' })
if (await d.isVisible().catch(() => false)) await d.click()
await page.getByRole('button', { name: 'Settings' }).first().click(); await page.waitForTimeout(1000)
await page.getByRole('button', { name: /Ondas+.*Start Free Trial/s }).click(); await page.waitForTimeout(700); await page.getByRole('button', { name: 'Start Free Trial' }).click(); await page.waitForTimeout(900); await page.waitForTimeout(700)
await page.screenshot({ path: 'shots/v14-s.png' }); await page.getByRole('button', { name: /^Integrations/ }).first().click(); await page.waitForTimeout(900)
await page.getByRole('button', { name: /Calendar/ }).first().click(); await page.waitForTimeout(1200)
await page.screenshot({ path: 'shots/v14-calendar.png' })
const [dl] = await Promise.all([page.waitForEvent('download', { timeout: 8000 }).catch(() => null), page.getByRole('button', { name: 'Share or Add to Calendar' }).click()])
if (dl) { const p = await dl.path(); const fs = await import('fs'); const t = fs.readFileSync(p, 'utf8'); console.log('events', (t.match(/BEGIN:VEVENT/g) || []).length, 'alarms', (t.match(/BEGIN:VALARM/g) || []).length, 'immerse', /immerse-/.test(t)) } else console.log('no download')
await browser.close()
