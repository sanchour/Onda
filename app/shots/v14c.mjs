import { webkit, devices } from '@playwright/test'
const browser = await webkit.launch()
const ctx = await browser.newContext({ ...devices['iPhone 15 Pro'], colorScheme: 'dark' })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
await page.goto('http://localhost:4173/?seed=demo')
await page.getByText('Onda · Day 4 of 14').waitFor({ timeout: 90000 })
const d = page.getByRole('button', { name: 'Dismiss' })
if (await d.isVisible().catch(() => false)) await d.click()
await page.getByRole('button', { name: 'Settings' }).first().click(); await page.waitForTimeout(900)
await page.getByRole('button', { name: /^Appearance/ }).first().click(); await page.waitForTimeout(700)
await page.getByRole('radio', { name: 'Dark' }).click().catch(async () => { await page.getByText('Dark', { exact: true }).first().click() })
await page.waitForTimeout(600)
await page.getByRole('button', { name: 'Back' }).first().click(); await page.waitForTimeout(500)
await page.getByRole('button', { name: 'Back' }).first().click(); await page.waitForTimeout(800)
await page.getByRole('tab', { name: 'Tasks', exact: true }).click(); await page.waitForTimeout(800)
await page.evaluate(() => { for (const e of document.querySelectorAll('*')) if (e.scrollHeight > e.clientHeight + 50 && getComputedStyle(e).overflowY !== 'visible') e.scrollTop = 650 })
await page.waitForTimeout(500)
await page.screenshot({ path: 'shots/v14c-dark-tasks.png' })
console.log(JSON.stringify({ theme: await page.evaluate(() => document.documentElement.dataset.theme), errors }))
await browser.close()
