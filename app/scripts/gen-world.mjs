// Writes src/screens/worldLand.ts: the world's land as one SVG path in the maps' equirectangular frame (800 x 400),
// from Natural Earth via world-atlas. Run once after changing the detail: node scripts/gen-world.mjs [50m|110m] [tolerance]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { feature } from 'topojson-client'

const here = path.dirname(fileURLToPath(import.meta.url))
const res = process.argv[2] ?? '50m'
const tol = Number(process.argv[3] ?? 0.3) // in map units: 1 unit is 0.45 degrees
const topo = JSON.parse(fs.readFileSync(path.join(here, `../node_modules/world-atlas/land-${res}.json`), 'utf8'))
const land = feature(topo, topo.objects.land)

const W = 800
const H = 400
const proj = ([lng, lat]) => [((lng + 180) / 360) * W, ((90 - lat) / 180) * H]

// Douglas-Peucker on a ring of projected points
function simplify(pts, eps) {
  if (pts.length < 4) return pts
  const keep = new Uint8Array(pts.length)
  keep[0] = keep[pts.length - 1] = 1
  const stack = [[0, pts.length - 1]]
  while (stack.length) {
    const [a, b] = stack.pop()
    const [ax, ay] = pts[a]
    const [bx, by] = pts[b]
    const dx = bx - ax
    const dy = by - ay
    const len = Math.hypot(dx, dy) || 1
    let best = -1
    let dmax = 0
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len
      if (d > dmax) (dmax = d), (best = i)
    }
    if (dmax > eps && best > 0) {
      keep[best] = 1
      stack.push([a, best], [best, b])
    }
  }
  return pts.filter((_, i) => keep[i])
}
const area = (pts) => Math.abs(pts.reduce((s, [x, y], i) => { const [x2, y2] = pts[(i + 1) % pts.length]; return s + x * y2 - x2 * y }, 0)) / 2
const f1 = (n) => (Math.round(n * 10) / 10).toString()

let d = ''
let points = 0
const polys = land.features.flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates))
for (const poly of polys) {
  for (const ring of poly) {
    // a ring starts and ends on the same point, so split it at the point farthest from the start and simplify each half
    const all = ring.map(proj)
    let m = 0
    all.forEach(([x, y], i) => { if (Math.hypot(x - all[0][0], y - all[0][1]) > Math.hypot(all[m][0] - all[0][0], all[m][1] - all[0][1])) m = i })
    const pts = m ? [...simplify(all.slice(0, m + 1), tol), ...simplify(all.slice(m), tol).slice(1, -1)] : []
    // islands smaller than a fifth of a square unit vanish at every zoom the maps use
    if (pts.length < 4 || area(pts) < 0.2) continue
    points += pts.length
    d += 'M' + pts.map(([x, y]) => `${f1(x)} ${f1(y)}`).join('L') + 'Z'
  }
}
const out = `// Generated by scripts/gen-world.mjs from Natural Earth (public domain) via world-atlas ${res}, tolerance ${tol}. Do not edit.\nexport const WORLD_LAND = '${d}'\n`
fs.writeFileSync(path.join(here, '../src/screens/worldLand.ts'), out)
console.log(res, 'tol', tol, 'points', points, 'bytes', out.length)
